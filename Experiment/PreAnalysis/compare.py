"""Bracket the Cost(beta) curve by the state distribution it is measured on.

On-policy distillation visits states generated by the student, which starts at the
anchor and drifts toward the target. Measuring on anchor states gives the cost at the
start of training; measuring on teacher states gives an upper bracket for a student
that has drifted all the way over.
"""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from WorkPlace.Distill_start.Experiment.PreAnalysis.common import OUT
from WorkPlace.Distill_start.Experiment.PreAnalysis.report import SWEEP, TOY, BETA_KNEE, position_bins, training_weighted


def curve(tag):
    suffix = f".{tag}" if tag else ""
    df = pd.read_parquet(os.path.join(OUT, f"cost_states{suffix}.parquet"))
    lengths = [len(json.loads(l)["output_ids"])
               for l in open(os.path.join(OUT, f"rollouts{suffix}.jsonl"))]
    return training_weighted(df, lengths, position_bins(df)).sort_index(), df


base, df_b = curve("")
teach, df_t = curve("teacherstates")

lines = ["# Cost(beta): how much does the state distribution matter?\n",
         "On-policy distillation visits states the student generates. At the start the student "
         "is the anchor; as training proceeds it drifts toward the target. The two columns "
         "bracket that drift.\n",
         "| beta | anchor states (t=0) | teacher states (upper bracket) | ratio | toy |",
         "|---|---|---|---|---|"]
for b in SWEEP:
    lines.append(f"| {b} | {base[b]:.3f} | {teach[b]:.3f} | {teach[b]/base[b]:.1f}x | {TOY[b]:.3f} |")
lines += ["",
          f"At the canonical beta=0.4 the bracket is [{base[0.4]:.3f}, {teach[0.4]:.3f}] nats, "
          f"i.e. the target sits between {np.exp(base[0.4]):.2f}x and {np.exp(teach[0.4]):.2f}x "
          f"off the teacher per token depending on how far the student has drifted.",
          "",
          "Per-kind means (unweighted), showing where the gap comes from:", "",
          "| state kind | anchor states | teacher states | ratio |", "|---|---|---|---|"]
for k in ("opening", "early", "internal"):
    a = df_b[(df_b.beta == 0.4) & (df_b.kind == k)].cost.mean()
    t = df_t[(df_t.beta == 0.4) & (df_t.kind == k)].cost.mean()
    lines.append(f"| {k} | {a:.3f} | {t:.3f} | {t/a:.1f}x |")

ab = df_b[df_b.beta == 0.4]
at = df_t[df_t.beta == 0.4]
lines += ["",
          f"The opening state is literally the same state in both runs (only the prompt), so it "
          f"matches; the gap is entirely in the generated region. Median internal cost is "
          f"{ab[ab.kind=='internal'].cost.median():.4f} on anchor states versus "
          f"{at[at.kind=='internal'].cost.median():.4f} on teacher states.\n"]

path = os.path.join(OUT, "compare.md")
open(path, "w").write("\n".join(lines))
print("\n".join(lines))

sns.set_theme(style="whitegrid", context="talk")
fig, ax = plt.subplots(figsize=(8, 5.5))
ax.fill_between(base.index, base.values, teach.values, alpha=.18, color="steelblue",
                label="reachable range during training")
ax.plot(base.index, base.values, "o-", label="anchor states (start of training)")
ax.plot(teach.index, teach.values, "^-", color="darkorange", label="teacher states (upper bracket)")
ax.plot(list(TOY), list(TOY.values()), "s--", color="gray", label="toy model")
ax.axvline(BETA_KNEE, color="crimson", ls=":", label=f"knee {BETA_KNEE}")
ax.set(xlabel=r"$\beta$", ylabel=r"$\mathrm{KL}(q^*\|\pi_T)$ [nats]",
       title="Cost bracket by state distribution")
ax.set_yscale("log"); ax.legend(fontsize=11)
fig.tight_layout()
fig.savefig(os.path.join(OUT, "cost_bracket.png"), dpi=150)
print(f"\nwrote {path} and cost_bracket.png")
