"""Step 4: read the Cost(beta) measurement and write the budget table + figures.

The headline number is a training-weighted mean: during distillation every token
position of every rollout is visited once, so the average that matters weights each
position by how often it occurs, not by how often we sampled it.
"""
import argparse
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from WorkPlace.Distill_start.Experiment.PreAnalysis.common import OUT

SWEEP = [0.1, 0.2, 0.4, 0.8]
TOY = {0.1: 0.004, 0.2: 0.026, 0.4: 0.10, 0.8: 0.37}  # toy_sims/beta_design.py
BETA_KNEE = 0.37


def position_bins(df):
    """Map each sampled position to the block of real positions it stands for."""
    pos = np.sort(df.pos.unique())
    edges = {}
    for i, p in enumerate(pos):
        lo = p if i == 0 else (pos[i - 1] + p) // 2 + 1
        hi = pos[-1] if i == len(pos) - 1 else (p + pos[i + 1]) // 2
        edges[p] = (lo, hi)
    return edges


def training_weighted(df, lengths, edges):
    """Mean cost over the position distribution actually visited during distillation."""
    lengths = np.asarray(lengths)
    out = {}
    for beta, g in df.groupby("beta"):
        per_pos = g.groupby("pos").cost.mean()
        total, count = 0.0, 0
        tail = per_pos.loc[per_pos.index >= 128].mean() if (per_pos.index >= 128).any() else per_pos.iloc[-1]
        for p, c in per_pos.items():
            lo, hi = edges[p]
            n = int((np.minimum(lengths, hi) - lo + 1).clip(0).sum())
            total += c * n
            count += n
        # positions past the sampled range keep the flat tail level
        beyond = int((lengths - max(per_pos.index)).clip(0).sum())
        total += tail * beyond
        count += beyond
        out[beta] = total / max(count, 1)
    return pd.Series(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="")
    ap.add_argument("--gen-label", default="anchor (Qwen3-1.7B-Base)",
                    help="which model generated the states these costs are measured on")
    args = ap.parse_args()
    suffix = f".{args.tag}" if args.tag else ""

    df = pd.read_parquet(os.path.join(OUT, f"cost_states{suffix}.parquet"))
    rollouts = [json.loads(l) for l in open(os.path.join(OUT, f"rollouts{suffix}.jsonl"))]
    lengths = [len(r["output_ids"]) for r in rollouts]
    edges = position_bins(df)
    tw = training_weighted(df, lengths, edges)

    by_kind = df.pivot_table(index="beta", columns="kind", values="cost", aggfunc="mean")
    per_pos = df.pivot_table(index="pos", columns="beta", values="cost", aggfunc="mean")
    fmt = df[df.kind == "opening"].pivot_table(index="beta", values="q_at_Ttop1", aggfunc="mean")
    bind = df.pivot_table(index="beta", columns="kind", values="mass_bind", aggfunc="mean")

    lines = []
    w = lines.append
    w("# Cost(beta) pre-analysis\n")
    w(f"Teacher Qwen3-14B (thinking), anchor Qwen3-1.7B-Base, MATH train. "
      f"{df.state_id.nunique()} states sampled from {len(rollouts)} rollouts generated by "
      f"{args.gen_label}, median length {int(np.median(lengths))} tokens. "
      f"{df.beta.nunique()} beta values.\n")

    degen = sum(1 for r in rollouts if len(r["output_ids"]) < 20)
    capped = sum(1 for r in rollouts if len(r["output_ids"]) >= 1024)
    w(f"## Rollout statistics ({args.gen_label})\n")
    w(f"- {len(rollouts)-degen}/{len(rollouts)} rollouts are real solution attempts; "
      f"{degen} ({100*degen/len(rollouts):.1f}%) degenerate into a few junk tokens and stop.")
    w(f"- {capped} ({100*capped/len(rollouts):.1f}%) hit the 1024-token cap; "
      f"length percentiles 25/50/75 = {int(np.percentile(lengths,25))}/"
      f"{int(np.percentile(lengths,50))}/{int(np.percentile(lengths,75))}.")
    w("")

    w("## Budget table\n")
    w("| beta | training-weighted | opening (pos 0) | early (1-12) | internal (16-512) | toy |")
    w("|---|---|---|---|---|---|")
    for b in SWEEP:
        row = by_kind.loc[b]
        w(f"| {b} | **{tw[b]:.3f}** | {row.get('opening', float('nan')):.2f} | "
          f"{row.get('early', float('nan')):.3f} | {row.get('internal', float('nan')):.3f} | {TOY[b]:.3f} |")
    w("")
    w(f"Training-weighted Cost(0.4) = {tw[0.4]:.3f} nats, i.e. the target that distillation "
      f"chases sits e^{tw[0.4]:.3f} = {np.exp(tw[0.4]):.2f}x off the teacher per token on average.\n")

    share = {}
    for b in SWEEP:
        pp = df[df.beta == b].groupby("pos").cost.mean()
        n0 = int((np.asarray(lengths) >= 0).sum())
        tot = tw[b] * sum(lengths)
        share[b] = pp.loc[0] * n0 / tot
    w(f"Position 0 alone carries {100*share[0.4]:.0f}% of the total cost at beta=0.4 while "
      f"being {100*len(rollouts)/sum(lengths):.1f}% of the visited positions: the teacher opens "
      f"deterministically with `<think>` and the anchor never does, so the floor pays for a "
      f"format token rather than a reasoning alternative.\n")

    w("## Format retention at the opening state\n")
    w("The teacher opens deterministically with `<think>`; the anchor never does. "
      "q*(teacher argmax) is the probability the distilled target leaves on that token.\n")
    w("| beta | " + " | ".join(str(b) for b in SWEEP) + " |")
    w("|---|" + "---|" * len(SWEEP))
    w("| q*(`<think>`) | " + " | ".join(f"{fmt.loc[b, 'q_at_Ttop1']:.3f}" for b in SWEEP) + " |")
    w("")
    w("The relation is exactly 1 - beta, and it is analytic rather than empirical: where the "
      "teacher is deterministic on a token the anchor ignores, every other token binds, so the "
      "floor moves exactly beta of the mass off the teacher's choice. A distilled student that "
      "reaches this target opens in the teacher's format 1 - beta of the time.\n")

    w("## Cost by position\n")
    w("| pos | " + " | ".join(f"beta={b}" for b in SWEEP) + " |")
    w("|---|" + "---|" * len(SWEEP))
    for p in per_pos.index:
        w(f"| {p} | " + " | ".join(f"{per_pos.loc[p, b]:.3f}" for b in SWEEP) + " |")
    w("")

    w("## Binding mass (share of target mass sitting on the floor)\n")
    w("| beta | " + " | ".join(bind.columns) + " |")
    w("|---|" + "---|" * len(bind.columns))
    for b in SWEEP:
        w(f"| {b} | " + " | ".join(f"{bind.loc[b, k]:.3f}" for k in bind.columns) + " |")
    w("")

    w("## Readout\n")
    ratio = tw[0.4] / TOY[0.4]
    w(f"1. Order of magnitude: training-weighted Cost(0.4) = {tw[0.4]:.3f} vs toy {TOY[0.4]:.3f} "
      f"({ratio:.1f}x). {'Same order.' if ratio < 10 else 'One order higher.'}")
    curve = tw.sort_index()
    w(f"2. Curve shape around the knee (beta_knee = {BETA_KNEE}): "
      + ", ".join(f"{b}->{curve[b]:.3f}" for b in curve.index if b in (0.2, 0.3, 0.35, 0.4, 0.45, 0.5)))
    w(f"3. Forecast for the sweep, recorded before any training run: "
      + ", ".join(f"beta={b}: {tw[b]:.3f} nats" for b in SWEEP) + ".")
    w("")

    path = os.path.join(OUT, f"report{suffix}.md")
    open(path, "w").write("\n".join(lines))
    tw.rename("training_weighted_cost").to_csv(os.path.join(OUT, f"cost_curve{suffix}.csv"))
    print("\n".join(lines))
    print(f"\nwrote {path}")

    sns.set_theme(style="whitegrid", context="talk")
    fig, axes = plt.subplots(1, 3, figsize=(19, 5.2))

    ax = axes[0]
    ax.plot(curve.index, curve.values, "o-", label="measured (training-weighted)")
    ax.plot(list(TOY), list(TOY.values()), "s--", color="gray", label="toy model")
    ax.axvline(BETA_KNEE, color="crimson", ls=":", label=f"knee {BETA_KNEE}")
    ax.set(xlabel=r"$\beta$", ylabel=r"$\mathrm{KL}(q^*\|\pi_T)$ [nats]", title="Cost curve")
    ax.set_yscale("log"); ax.legend(fontsize=11)

    ax = axes[1]
    for b in SWEEP:
        ax.plot(per_pos.index, per_pos[b], "o-", ms=4, label=rf"$\beta$={b}")
    ax.set(xlabel="position in rollout", ylabel="mean cost [nats]", title="Cost by position")
    ax.set_yscale("log"); ax.set_xscale("symlog", linthresh=1)
    ax.set_xlim(-0.2, per_pos.index.max() * 1.15); ax.legend(fontsize=11)

    ax = axes[2]
    ax.plot(fmt.index, fmt.q_at_Ttop1, "o-", color="darkorange")
    ax.axvline(BETA_KNEE, color="crimson", ls=":")
    ax.set(xlabel=r"$\beta$", ylabel=r"$q^*(\langle think\rangle)$", ylim=(0, 1.02),
           title="Format retention at pos 0")

    fig.tight_layout()
    fig.savefig(os.path.join(OUT, f"cost_beta{suffix}.png"), dpi=150)
    print(f"wrote {os.path.join(OUT, f'cost_beta{suffix}.png')}")


if __name__ == "__main__":
    main()
